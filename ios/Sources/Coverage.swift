import CoreLocation
import MapKit

/// **Is this point somewhere Sunday Drive covers?** Answered on the phone, from
/// an outline shipped inside the app, and the coordinate goes nowhere.
///
/// The covered area is the 48 contiguous states and Washington, DC. The answer
/// is still an outline, never a box: a box round the 48 states takes in
/// Toronto, Vancouver, Tijuana and the Gulf of Mexico, and the coverage really
/// does stop at those borders and coasts. Rectangles are for ranking search,
/// never for deciding what is in. See `docs/app-goes-national.md`.
///
/// The outline is the 48 states and DC from the Census Bureau's public-domain
/// cartographic boundaries, unioned, pushed 500 m out to sea and over each
/// border, and simplified, with the same margins the New England outline had.
/// `CoverageBoundary.swift` is generated by `ios/scripts/build_coverage_boundary.py`,
/// and its header records exactly what was done and what was measured. So a
/// point a few hundred metres over the line into Canada or Mexico counts as
/// inside, and that is why a search result is also checked by its state
/// (`accepts`).
enum Coverage {

    /// What the app calls the covered area, in copy.
    static let areaName = "the 48 contiguous states and Washington, DC"

    /// Whether a coordinate is in the covered area, or within a few hundred
    /// metres of its coasts or borders.
    ///
    /// A bounding box first, then a crossing test over only the rings whose
    /// own boxes hold the point, and within a ring only the edges in the
    /// point's band of latitude. The mainland ring has about 16,000 vertices,
    /// so the bands are what keep this cheap enough for every fix and every
    /// keystroke (`CoverageTests.test_the_test_is_cheap`).
    static func contains(_ coordinate: CLLocationCoordinate2D) -> Bool {
        let lat = coordinate.latitude, lon = coordinate.longitude
        // Also rejects NaN, since every comparison with it is false.
        guard lat >= CoverageBoundary.south, lat <= CoverageBoundary.north,
              lon >= CoverageBoundary.west, lon <= CoverageBoundary.east
        else { return false }
        return rings.contains { $0.contains(lat: lat, lon: lon) }
    }

    /// The 48 contiguous states and DC, by postal code.
    static let stateCodes: Set<String> = [
        "AL", "AZ", "AR", "CA", "CO", "CT", "DE", "FL", "GA", "ID", "IL", "IN", "IA",
        "KS", "KY", "LA", "ME", "MD", "MA", "MI", "MN", "MS", "MO", "MT", "NE", "NV",
        "NH", "NJ", "NM", "NY", "NC", "ND", "OH", "OK", "OR", "PA", "RI", "SC", "SD",
        "TN", "TX", "UT", "VT", "VA", "WA", "WV", "WI", "WY", "DC",
    ]

    // MARK: - What the app says

    /// For a search that found places, none of them in the covered area.
    static func notCovered(_ label: String) -> String {
        "“\(label)” is outside the area Sunday Drive covers: \(areaName)."
    }

    /// For My Location, or the Loop row, with the phone outside.
    static let outsideHere = "You’re outside the area Sunday Drive covers, so this can’t start "
        + "from your location. Type a town in the 48 contiguous states as your start."

    // MARK: - Resolving a search

    /// The first search result that is in the covered area, or nil.
    ///
    /// **The hard guarantee.** Suggestions are only filtered by what their
    /// labels say, and a typed search only ranked, so this is the one place
    /// that decides what becomes a start or a destination, on every iOS
    /// version. "The first covered" rather than "the first": a name shared by
    /// places in and out of coverage comes back in whatever order Apple ranks
    /// it.
    static func firstInside(_ items: [MKMapItem]) -> MKMapItem? {
        items.first { accepts($0.placemark.coordinate, administrativeArea: $0.placemark.administrativeArea) }
    }

    /// A result is in when it is inside the outline and, if it names a state
    /// or province, names one of the 48 or DC.
    ///
    /// The state is checked as well because the outline reaches a few hundred
    /// metres over each border: Stanstead, Quebec, and the Tijuana side of the
    /// San Ysidro crossing are inside it.
    static func accepts(_ coordinate: CLLocationCoordinate2D, administrativeArea: String?) -> Bool {
        guard contains(coordinate) else { return false }
        guard let area = administrativeArea?.trimmingCharacters(in: .whitespaces),
              !area.isEmpty else { return true }
        return stateCodes.contains(area.uppercased()) || stateNames.contains(area.lowercased())
    }

    private static let stateNames: Set<String> = [
        "alabama", "arizona", "arkansas", "california", "colorado", "connecticut",
        "delaware", "florida", "georgia", "idaho", "illinois", "indiana", "iowa",
        "kansas", "kentucky", "louisiana", "maine", "maryland", "massachusetts",
        "michigan", "minnesota", "mississippi", "missouri", "montana", "nebraska",
        "nevada", "new hampshire", "new jersey", "new mexico", "new york",
        "north carolina", "north dakota", "ohio", "oklahoma", "oregon", "pennsylvania",
        "rhode island", "south carolina", "south dakota", "tennessee", "texas", "utah",
        "vermont", "virginia", "washington", "west virginia", "wisconsin", "wyoming",
        "district of columbia",
    ]

    // MARK: - Filtering suggestions

    /// Whether to show an autocomplete suggestion, judged by its label alone.
    ///
    /// A suggestion carries no coordinate, only the two strings Apple shows,
    /// so this reads them. **Built from strings captured on the iOS 26.4
    /// simulator**, not imagined ones, and those disagreed with the obvious
    /// design in two ways:
    ///
    /// - **A city's state is in its title, not its subtitle.** "Portland, OR"
    ///   comes back over the subtitle "United States".
    /// - **`regionPriority = .required` does not restrict the completer.**
    ///   With the region pinned, "Times Square" still offered Mumbai and
    ///   "Paris" still offered France. The restriction works for a typed
    ///   search (`MKLocalSearch`) and not here, so on every iOS version this
    ///   filter is the whole of the defence for suggestions. `firstInside`
    ///   stands behind it.
    ///
    /// The rule: find the last state or province code in the subtitle, or
    /// failing that at the end of the title. One of the 48 or DC keeps the
    /// suggestion; any other code (a Canadian province, or a US state or
    /// territory outside the 48) drops it. With no code at all, a subtitle
    /// that ends in a foreign country's name, or in the name of a US state or
    /// territory outside the 48, drops it, and anything else is kept: a bare
    /// street address ("65-66 Beacon St") is how some Boston results arrive.
    static func allowsSuggestion(title: String, subtitle: String) -> Bool {
        if let code = lastRegionCode(in: subtitle) ?? trailingRegionCode(in: title) {
            return stateCodes.contains(code)
        }
        // The last part of the subtitle, or of the title when the subtitle is
        // empty: captured 2026-10-18, "San Juan, Argentina" arrives over "".
        let place = subtitle.trimmingCharacters(in: .whitespaces).isEmpty ? title : subtitle
        guard let last = place.split(separator: ",").last?
                .trimmingCharacters(in: .whitespaces).lowercased()
        else { return true }
        return !foreignCountryNames.contains(last) && !otherRegionNames.contains(last)
    }

    /// The names of the US states and territories outside the 48, as a
    /// subtitle can end with one and no code: captured 2026-10-18, "Honolulu"
    /// arrives over "Kona, Hawaiʻi". With and without the ʻokina.
    private static let otherRegionNames: Set<String> = [
        "alaska", "hawaii", "hawaiʻi", "hawai\u{2018}i", "hawai'i", "puerto rico",
        "u.s. virgin islands", "us virgin islands", "guam", "american samoa",
        "northern mariana islands",
    ]

    /// The last code in a subtitle, scanning its comma-separated parts.
    private static func lastRegionCode(in text: String) -> String? {
        text.split(separator: ",").compactMap { regionCode(in: String($0)) }.last
    }

    /// A code that is the whole last part of a title, as in "Portland, OR".
    /// Only the last part, so a business named after a place keeps its name.
    private static func trailingRegionCode(in title: String) -> String? {
        let parts = title.split(separator: ",")
        guard parts.count > 1, let last = parts.last else { return nil }
        return regionCode(in: String(last))
    }

    /// A state or province code inside one part of an address.
    ///
    /// A code is two capital letters followed by nothing but a postal code,
    /// which covers every shape captured: "MA", "MA  02114", "OR 97218-1009",
    /// "Montréal QC", "Sherbrooke QC J1K 2R1". It is matched as a whole word,
    /// so the letters "ME" inside a word are not Maine, and "NE" in
    /// "7000 NE Airport Way" is a direction, not Nebraska.
    private static func regionCode(in part: String) -> String? {
        let words = part.split(whereSeparator: \.isWhitespace).map(String.init)
        for (index, word) in words.enumerated() where isCode(word) {
            let rest = words[(index + 1)...]
            if rest.isEmpty || isUSPostalCode(rest) || isCanadianPostalCode(rest) {
                return word
            }
        }
        return nil
    }

    private static func isCode(_ word: String) -> Bool {
        word.count == 2 && (stateCodes.contains(word) || otherRegionCodes.contains(word))
    }

    /// "02114" or "97218-1009".
    private static func isUSPostalCode(_ words: ArraySlice<String>) -> Bool {
        guard words.count == 1, let zip = words.first else { return false }
        let digits = zip.split(separator: "-", omittingEmptySubsequences: false)
        return digits.first?.count == 5
            && digits.allSatisfy { !$0.isEmpty && $0.allSatisfy(\.isASCII) && $0.allSatisfy(\.isNumber) }
    }

    /// "J1K 2R1": letter, digit, letter, then digit, letter, digit.
    private static func isCanadianPostalCode(_ words: ArraySlice<String>) -> Bool {
        let joined = words.joined()
        guard joined.count == 6 else { return false }
        return joined.enumerated().allSatisfy { index, character in
            character.isASCII && (index.isMultiple(of: 2) ? character.isLetter : character.isNumber)
        }
    }

    /// The codes that mean "somewhere else": the US states and territories
    /// outside the 48, and every Canadian province and territory.
    private static let otherRegionCodes: Set<String> = [
        "AK", "HI", "PR", "VI", "GU", "AS", "MP",
        "AB", "BC", "MB", "NB", "NL", "NS", "NT", "NU", "ON", "PE", "QC", "SK", "YT",
    ]

    /// Every country's name except the United States', in the phone's
    /// language and in English, plus the four the UK is written as.
    ///
    /// Country names are localised, so nothing here depends on recognising
    /// "United States". That is why this only ever *drops*: a name it does not
    /// know is kept and left to `firstInside`.
    private static let foreignCountryNames: Set<String> = {
        let languages = [Locale.current, Locale(identifier: "en_US")]
        var names: Set<String> = ["england", "scotland", "wales", "northern ireland"]
        for region in Locale.Region.isoRegions {
            let code = region.identifier
            guard code.count == 2, code.allSatisfy(\.isLetter), code != "US" else { continue }
            for language in languages {
                if let name = language.localizedString(forRegionCode: code) {
                    names.insert(name.lowercased())
                }
            }
        }
        for language in languages {
            if let us = language.localizedString(forRegionCode: "US") { names.remove(us.lowercased()) }
        }
        return names
    }()

    // MARK: - Ranking search

    /// Where to rank search results, and whether to insist on that region.
    struct SearchBias {
        let region: MKCoordinateRegion
        /// True when `region` is the coverage envelope standing in for a bias
        /// that had left the covered area.
        let restricted: Bool
    }

    /// The region to rank a search around, kept to the covered area.
    ///
    /// **A bias that shows some of the covered area is kept**, because
    /// completions rank by distance from the region's centre, and that is
    /// what stops "main street" offering one four towns away
    /// (`MKCoordinateRegion.around`). Its centre need not be covered: the map
    /// centred on the water off Key West, or on Windsor with Detroit across
    /// the river, still ranks the covered places it shows first. Around New
    /// England the centre alone decided, and nationally that would rank a
    /// search from the Florida Keys from Kansas.
    ///
    /// **A bias that shows none of it is replaced by the envelope**: the map
    /// over Toronto after its locate button, or the 30 km box around a fix
    /// taken there. So is one wider than the whole area, the opening camera.
    ///
    /// Only the envelope is ever made `.required`. Required on the 30 km box,
    /// "Moab, UT" typed in Denver would find nothing.
    static func searchBias(around region: MKCoordinateRegion) -> SearchBias {
        let envelope = MKCoordinateRegion.coverageEnvelope
        let tooWide = region.span.latitudeDelta > envelope.span.latitudeDelta
            || region.span.longitudeDelta > envelope.span.longitudeDelta
        if tooWide || !showsSomeOf(region) {
            return SearchBias(region: envelope, restricted: true)
        }
        return SearchBias(region: region, restricted: false)
    }

    /// Whether any of a region is covered, judged by its centre and then a
    /// 5 × 5 grid of points across it. A sliver of coast between grid points
    /// can be missed, which costs only ranking, never what is let in.
    static func showsSomeOf(_ region: MKCoordinateRegion) -> Bool {
        if contains(region.center) { return true }
        let steps = 5
        for row in 0..<steps {
            for column in 0..<steps {
                let point = CLLocationCoordinate2D(
                    latitude: region.center.latitude
                        + region.span.latitudeDelta * (Double(row) / Double(steps - 1) - 0.5),
                    longitude: region.center.longitude
                        + region.span.longitudeDelta * (Double(column) / Double(steps - 1) - 0.5))
                if contains(point) { return true }
            }
        }
        return false
    }

    // MARK: - The outline

    private static let rings: [Ring] = CoverageBoundary.rings.map(Ring.init)

    /// One closed ring of the outline, with its bounding box and an index of
    /// its edges by latitude.
    private struct Ring {
        /// Latitude, longitude pairs, flattened, as generated.
        let points: [Double]
        let south: Double, north: Double, west: Double, east: Double
        /// Edge `i` joins vertex `i - 1` to vertex `i` (vertex 0 to the last).
        /// `bands[b]` lists every edge whose latitude range overlaps band `b`,
        /// and only an edge spanning the point's latitude can cross its ray,
        /// so the test reads one band instead of the whole ring.
        private let bands: [[Int32]]
        private let bandHeight: Double

        init(_ points: [Double]) {
            self.points = points
            let count = points.count / 2
            let lats = stride(from: 0, to: points.count, by: 2).map { points[$0] }
            let lons = stride(from: 1, to: points.count, by: 2).map { points[$0] }
            let south = lats.min() ?? 0
            self.south = south; north = lats.max() ?? 0
            west = lons.min() ?? 0; east = lons.max() ?? 0

            // About eight vertices a band on average; long thin rings put
            // more in some bands, which costs time and never correctness.
            let bandCount = max(1, count / 8)
            let height = max((north - south) / Double(bandCount), 1e-9)
            func band(_ lat: Double) -> Int {
                min(bandCount - 1, max(0, Int((lat - south) / height)))
            }
            var bands = Array(repeating: [Int32](), count: bandCount)
            for i in 0..<count {
                let j = i == 0 ? count - 1 : i - 1
                let a = points[2 * i], b = points[2 * j]
                for k in band(min(a, b))...band(max(a, b)) { bands[k].append(Int32(i)) }
            }
            self.bands = bands
            bandHeight = height
        }

        /// Even-odd crossing test, treating degrees as planar. The edges are
        /// a couple of hundred metres long, so the curve of the earth between
        /// two vertices is far inside the 10 m the vertices were rounded to.
        func contains(lat: Double, lon: Double) -> Bool {
            guard lat >= south, lat <= north, lon >= west, lon <= east else { return false }
            let count = points.count / 2
            let band = min(bands.count - 1, max(0, Int((lat - south) / bandHeight)))
            var inside = false
            for edge in bands[band] {
                let i = Int(edge), j = i == 0 ? count - 1 : i - 1
                let latI = points[2 * i], lonI = points[2 * i + 1]
                let latJ = points[2 * j], lonJ = points[2 * j + 1]
                if (latI > lat) != (latJ > lat) {
                    let crossing = lonI + (lat - latI) / (latJ - latI) * (lonJ - lonI)
                    if lon < crossing { inside.toggle() }
                }
            }
            return inside
        }
    }
}

/// Whether the phone is in the covered area, as of the last fix the app
/// looked at.
///
/// Kept in one place, on the `LocationManager` both planning models share, and
/// written by every fix the app plans with: the check at launch and both
/// My Location paths. Home's Loop row reads it.
enum RegionStatus: Equatable {
    case unknown
    case inside
    case outside

    init(_ coordinate: CLLocationCoordinate2D) {
        self = Coverage.contains(coordinate) ? .inside : .outside
    }
}

// MARK: - Applying the bias

extension MKLocalSearch.Request {
    /// Rank this search around `region`, kept to the covered area. See
    /// `Coverage.searchBias`.
    func rank(around region: MKCoordinateRegion) {
        let bias = Coverage.searchBias(around: region)
        self.region = bias.region
        if #available(iOS 18, *) { regionPriority = bias.restricted ? .required : .default }
    }
}

extension MKLocalSearchCompleter {
    /// Rank completions around `region`, kept to the covered area.
    ///
    /// **No `regionPriority`, deliberately**, though the typed search gets one.
    /// Measured on iOS 26.4, `.required` does not restrict the completer: with
    /// the region pinned to New England "Times Square" still offered Mumbai,
    /// and in the one query of 24 where it changed anything it pushed a wanted
    /// result off the five rows the field shows. `allowsSuggestion` is what
    /// keeps places outside coverage out of the list.
    func rank(around region: MKCoordinateRegion) {
        self.region = Coverage.searchBias(around: region).region
    }
}
